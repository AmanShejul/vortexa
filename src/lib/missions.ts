export const missions: Mission[] = missionDefinitions.map((mission) => ({
  ...mission,
  slug: mission.id,
  topic: mission.concepts[0],
  hintMetadata: {
    focusAreas: [...mission.concepts],
    commonPitfalls: mission.constraints.slice(0, 2),
  },
}));

export function getMission(missionId: string): Mission | undefined {
  return missions.find((mission) => mission.id === missionId);
}
